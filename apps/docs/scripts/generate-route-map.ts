#!/usr/bin/env tsx
/**
 * Generate a route map from the SvelteKit routes directory
 */
import * as fs from 'fs/promises';
import { glob } from 'glob';
import * as path from 'path';
import { GENERATED_OUTPUT, REPO_ROOT, ROUTES_DIR } from './docs-scripts.config';
import { isMainModule } from './utils/cli';

interface RouteNode {
  path: string;
  fullPath: string;
  type: 'page' | 'layout' | 'server' | 'error' | 'group' | 'param' | 'dir';
  children: Array<RouteNode>;
}

/**
 * Write the route map into the output directory.
 * @param options.outputDir - Where the map's `README.md` is written.
 */
export async function generateRouteMap({
  outputDir = GENERATED_OUTPUT.routes
}: { outputDir?: string } = {}): Promise<void> {
  console.info('Generating route map...\n');

  const outputFile = path.join(outputDir, 'README.md');
  const tree = await buildRouteTree();
  const markdown = generateMarkdown(tree);

  // Start from an empty directory, so nothing an earlier run left there is moved into the site
  await fs.rm(outputDir, { recursive: true, force: true });
  await fs.mkdir(outputDir, { recursive: true });
  await fs.writeFile(outputFile, markdown, 'utf-8');

  console.info(`✓ Route map generated: ${outputFile}`);
}

/**
 * Build a tree structure from route paths
 */
async function buildRouteTree(): Promise<RouteNode> {
  const root: RouteNode = {
    path: 'routes',
    fullPath: ROUTES_DIR,
    type: 'dir',
    children: []
  };

  // Every directory that holds a route file
  const files = await glob(`${ROUTES_DIR}/**/*.{svelte,ts,js}`, {
    ignore: ['**/node_modules/**']
  });
  const dirs = Array.from(new Set(files.map((file) => path.dirname(file)))).sort();

  for (const dir of dirs) {
    const relativePath = path.relative(ROUTES_DIR, dir);
    if (relativePath === '') continue;

    const segments = relativePath.split(path.sep);
    let current = root;

    // Navigate/create tree structure
    for (let i = 0; i < segments.length; i++) {
      const segment = segments[i];
      const { name, type } = parseSegment(segment);

      let child = current.children.find((c) => c.path === name);

      if (!child) {
        child = {
          path: name,
          fullPath: path.join(ROUTES_DIR, segments.slice(0, i + 1).join(path.sep)),
          type,
          children: []
        };
        current.children.push(child);
      }

      current = child;
    }
  }

  return root;
}

/**
 * Parse route segment to identify special types
 */
function parseSegment(segment: string): { name: string; type: RouteNode['type'] } {
  // Dynamic parameter: [param] or [param=matcher]
  if (segment.startsWith('[') && segment.endsWith(']')) {
    return { name: segment, type: 'param' };
  }

  // Route group: (group)
  if (segment.startsWith('(') && segment.endsWith(')')) {
    return { name: segment.slice(1, -1), type: 'group' };
  }

  return { name: segment, type: 'dir' };
}

/**
 * Generate markdown for route tree
 */
function generateMarkdown(tree: RouteNode): string {
  const lines: Array<string> = [];

  lines.push('# Route Map\n');
  lines.push(
    `This is an automatically generated map of the route directories under \`${path.relative(REPO_ROOT, ROUTES_DIR).replace(/\\/g, '/')}\`, the frontend's SvelteKit routes. ` +
      'A name in parentheses is a route group, which adds no URL segment; a name in brackets is a route parameter, and double brackets mark an optional one. ' +
      'The page is regenerated by `yarn workspace @openvaa/docs generate:docs`.\n'
  );
  lines.push('```');
  lines.push(...generateTreeLines(tree, '', true));
  lines.push('```');

  return lines.join('\n');
}

/**
 * Generate tree structure lines
 */
function generateTreeLines(node: RouteNode, prefix: string, isLast: boolean): Array<string> {
  const lines: Array<string> = [];
  const connector = isLast ? '└── ' : '├── ';
  const extension = isLast ? '    ' : '│   ';

  // A route group is shown in its parentheses
  const displayName = node.type === 'group' ? `(${node.path})` : node.path;
  lines.push(`${prefix}${connector}${displayName}/`);

  const childPrefix = prefix + extension;

  // Sort children
  const sortedChildren = [...node.children].sort((a, b) => {
    // Groups first, then params, then regular dirs
    if (a.type !== b.type) {
      if (a.type === 'group') return -1;
      if (b.type === 'group') return 1;
      if (a.type === 'param') return 1;
      if (b.type === 'param') return -1;
    }
    return a.path.localeCompare(b.path);
  });

  // Recurse for children
  sortedChildren.forEach((child, index) => {
    const isLastChild = index === sortedChildren.length - 1;
    lines.push(...generateTreeLines(child, childPrefix, isLastChild));
  });

  return lines;
}

if (isMainModule(import.meta.url)) {
  generateRouteMap().catch((error) => {
    console.error('Error generating route map:', error);
    process.exit(1);
  });
}
