import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { describe, expect, test } from 'vitest';
import { ORGANIZATION_MATCHING_METHODS } from '$lib/utils/organizationMatching';

/**
 * Calls every compiled Paraglide message in every locale and fails when one answers with its own key, which is what a compiled message returns when none of its variants matches its inputs.
 *
 * The inputs come from each locale's own declarations: a number that a variant is chosen by takes values that reach every plural category of the configured locales, 0 and 1 included; an input matched against other literals takes each literal its variants name; a date input takes one fixed date.
 *
 * The compiled index is imported by its file path, because `vitest.config.ts` aliases `$lib/paraglide/messages` to a stub. It is generated by the frontend build or by `yarn workspace @openvaa/frontend paraglide:compile`.
 */

const COMPILE_COMMAND = 'yarn workspace @openvaa/frontend paraglide:compile';

/**
 * The numbers every numeric input takes: together they reach every plural category of the configured locales.
 */
const NUMBERS: ReadonlyArray<number> = [0, 1, 2, 5, 21, 100, 1000000];
const DATE = '2026-01-15T12:00:00.000Z';
const TEXT = 'text';

const frontendRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..', '..', '..');
const messagesDir = path.join(frontendRoot, 'messages');
const compiledIndexPath = path.join(frontendRoot, 'src', 'lib', 'paraglide', 'messages', '_index.js');
const inlangSettings = JSON.parse(fs.readFileSync(path.join(frontendRoot, 'project.inlang', 'settings.json'), 'utf8'));
const baseLocale: string = inlangSettings.baseLocale;
const locales: Array<string> = inlangSettings.locales;
const pathPatterns: Array<string> = inlangSettings['plugin.inlang.messageFormat'].pathPattern;

type CompiledMessage = (inputs: Record<string, unknown>, options: { locale: string }) => unknown;

const compiled: Record<string, unknown> | undefined = fs.existsSync(compiledIndexPath)
  ? await import(/* @vite-ignore */ compiledIndexPath)
  : undefined;

interface Variant {
  declarations?: Array<string>;
  selectors?: Array<string>;
  match?: Record<string, string>;
}

function isMessageLeaf(value: unknown): boolean {
  return (
    typeof value === 'string' ||
    Array.isArray(value) ||
    (typeof value === 'object' &&
      value !== null &&
      ('declarations' in value || 'selectors' in value || 'match' in value))
  );
}

/**
 * Every message of one locale, keyed by its full translation key: each file's single top-level key is its namespace.
 */
function readCatalogue(locale: string): Map<string, unknown> {
  const messages = new Map<string, unknown>();
  function walk(tree: unknown, prefix: string): void {
    if (isMessageLeaf(tree)) {
      messages.set(prefix, tree);
      return;
    }
    if (typeof tree !== 'object' || tree === null) return;
    for (const [key, value] of Object.entries(tree)) walk(value, `${prefix}.${key}`);
  }
  for (const pattern of pathPatterns) {
    const filename = path.basename(pattern.split('{locale}').join(locale));
    const namespace = filename.replace(/\.json$/, '');
    const content = JSON.parse(fs.readFileSync(path.join(messagesDir, locale, filename), 'utf8'));
    walk(content[namespace], namespace);
  }
  return messages;
}

/**
 * The values each input of a message takes, read from its declarations and its variants' match keys, which the message-format plugin splits on commas.
 */
function inputValues(message: unknown): Record<string, ReadonlyArray<unknown>> {
  const values: Record<string, ReadonlyArray<unknown>> = {};
  if (typeof message === 'string') {
    for (const [, name] of message.matchAll(/\{\s*([A-Za-z_][A-Za-z0-9_]*)\s*\}/g)) values[name] = [TEXT];
    return values;
  }
  const variants: Array<Variant> = Array.isArray(message) ? message : [message as Variant];
  const inputs = new Set<string>();
  const numeric = new Set<string>();
  const dates = new Set<string>();
  const literals = new Map<string, Set<string>>();
  for (const variant of variants) {
    for (const declaration of variant.declarations ?? []) {
      const input = declaration.match(/^input\s+(\S+)$/);
      if (input) inputs.add(input[1]);
      const local = declaration.match(/^local\s+\S+\s*=\s*(\S+?)\s*:\s*(\S+)/);
      if (local?.[2] === 'plural') numeric.add(local[1]);
      if (local?.[2] === 'datetime') dates.add(local[1]);
    }
    for (const key of Object.keys(variant.match ?? {})) {
      for (const part of key.split(',')) {
        const separator = part.indexOf('=');
        if (separator < 0) continue;
        const name = part.slice(0, separator).trim();
        const value = part.slice(separator + 1).trim();
        if (value === '*') continue;
        if (!literals.has(name)) literals.set(name, new Set());
        literals.get(name)!.add(value);
      }
    }
  }
  for (const name of inputs) {
    const matched = [...(literals.get(name) ?? [])];
    if (numeric.has(name) || matched.some((value) => value !== '' && Number.isFinite(Number(value))))
      values[name] = NUMBERS;
    else if (dates.has(name)) values[name] = [DATE];
    else if (matched.length > 0) values[name] = matched;
    else values[name] = [TEXT];
  }
  return values;
}

/**
 * Every combination of the given input values.
 */
function combinations(values: Record<string, ReadonlyArray<unknown>>): Array<Record<string, unknown>> {
  return Object.entries(values).reduce<Array<Record<string, unknown>>>(
    (combos, [name, options]) => combos.flatMap((combo) => options.map((option) => ({ ...combo, [name]: option }))),
    [{}]
  );
}

const catalogues = new Map(locales.map((locale) => [locale, readCatalogue(locale)]));
const baseKeys = [...catalogues.get(baseLocale)!.keys()].sort();

test('the compiled message index exists', () => {
  expect(compiled, `${compiledIndexPath} is missing: run \`${COMPILE_COMMAND}\` first`).toBeDefined();
});

test.each(baseKeys)('%s', (key) => {
  if (!compiled) throw new Error(`${compiledIndexPath} is missing: run \`${COMPILE_COMMAND}\` first`);
  const fn = compiled[key];
  expect(typeof fn, `no compiled message exports the key ${key}`).toBe('function');
  const failures: Array<{ locale: string; inputs: Record<string, unknown> }> = [];
  for (const locale of locales) {
    const message = catalogues.get(locale)!.get(key) ?? catalogues.get(baseLocale)!.get(key);
    for (const inputs of combinations(inputValues(message))) {
      if ((fn as CompiledMessage)(inputs, { locale }) === key) failures.push({ locale, inputs });
    }
  }
  const named = failures.map(({ locale, inputs }) => `${locale} ${JSON.stringify(inputs)}`).join('; ');
  expect(failures.length, `${key} answers with its own key for: ${named}`).toBe(0);
});

/**
 * The key of the sentence the About page shows under its party-matching heading, with the page's matching method as `partyMatchingMethod`.
 */
const PARTY_MATCHING_KEY = 'about.organizationMatching.content';

/**
 * The text of the variant a method reaches in one locale's catalogue: the variant whose selector value is the method itself, otherwise the catch-all.
 */
function partyMatchingVariant(locale: string, method: string): string | undefined {
  const message =
    catalogues.get(locale)!.get(PARTY_MATCHING_KEY) ?? catalogues.get(baseLocale)!.get(PARTY_MATCHING_KEY);
  const variants: Array<Variant> = Array.isArray(message) ? message : [message as Variant];
  const match = variants[0]?.match ?? {};
  return match[`partyMatchingMethod=${method}`] ?? match['partyMatchingMethod=*'];
}

describe('the party-matching sentence, for every method the About page passes', () => {
  const methods = ORGANIZATION_MATCHING_METHODS.filter((method) => method !== 'none');
  const cases = locales.flatMap((locale) => methods.map((method) => [locale, method] as const));

  test.each(cases)('%s, %s', (locale, method) => {
    if (!compiled) throw new Error(`${compiledIndexPath} is missing: run \`${COMPILE_COMMAND}\` first`);
    const fn = compiled[PARTY_MATCHING_KEY] as CompiledMessage;
    const text = fn({ partyMatchingMethod: method }, { locale });
    expect(text, `${PARTY_MATCHING_KEY} answers with its own key for ${method} in ${locale}`).not.toBe(
      PARTY_MATCHING_KEY
    );
    expect(text).toBe(partyMatchingVariant(locale, method));
  });
});
