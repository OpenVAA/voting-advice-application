// rename.map.mjs — the ordered mapping table of Phase 170 (D-15). THE reviewable artefact of the phase.
//
// One object per row of 170-01-PLAN.md § mapping_table, in table order. A row that contains another
// row's match comes first. Every row is applied to file CONTENTS and to tracked PATHS (the move list
// of `rename.mjs --moves` is derived from these rows; no move is typed by hand).
//
//   id    the row id of the plan's table (P<plan>-<nn>, with a/b/c suffixes where a row holds
//         more than one pattern)
//   plan  the plan that applies the row; `rename.mjs --plan N` applies every row with plan <= N
//   from  a global JavaScript regular expression
//   to    a String.replace replacement string ('$$' is a literal '$', '$1' a capture)
//   only  optional predicate over the file's CURRENT repo-relative path
//   note  what the row is for
//
// Three properties hold, each checked by the tooling:
//   1. No row's output contains any row's input, so `rename.mjs --check` after an apply exits 0.
//   2. The two exemptions are structural: no row matches the snake-case RPC name
//      `get_candidate_user_data`, and no row matches a `candidate` preceded by a hyphen as in
//      `invite-candidate` (`170-verdict.mjs exemptions` counts both at the base revision and at HEAD).
//   3. The target namespace starts empty (`git grep -i contestant -- ':!.planning'` printed nothing at
//      the base revision, apart from the search gate's own source and fixtures).

